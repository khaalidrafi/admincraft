"""MCP server renderer — emits the standalone stdio server as one string.

The generated artifact is stdlib-only on purpose: users drop it next to
their project, point it at their API host, and register it with any
MCP-capable agent. No pip install, no framework imports. All backend
knowledge (resources, API host, tool schemas) is baked in at generation
time; the token is NOT baked — the server reads it from an env var so
secrets never land on disk in generated files.
"""

from __future__ import annotations

import json

# Tokens use __NAME__ (double underscore) because generated code is full
# of single braces; str.replace avoids brace-escaping hell.
_TEMPLATE = '''#!/usr/bin/env python3
"""__SERVER_NAME__ — MCP admin server (generated by admineverywhere build_mcp __VERSION__).

Speaks the MCP stdio protocol: newline-delimited JSON-RPC 2.0 on
stdin/stdout, protocol version __PROTOCOL__. Agents use it to run admin
tasks against the __API_HOST__ API: one CRUD tool-set per model resource
plus the runtime branding API.

Run it:
    __TOKEN_ENV__=<your-api-token> python3 __SERVER_NAME__.py

Register it with your MCP client (e.g. Claude Desktop, Cline):
    command: python3   args: ["/path/to/__SERVER_NAME__.py"]
    env: { "__TOKEN_ENV__": "<your-api-token>" }

The API token is read from the environment on every call — nothing is
hardcoded. Generated file: deterministic, safe to re-run build_mcp.
"""
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request

API_HOST = "__API_HOST__"
SERVER_NAME = "__SERVER_NAME__"
SERVER_VERSION = "__VERSION__"
PROTOCOL_VERSION = "__PROTOCOL__"
DEFAULT_TOKEN_ENV = "__TOKEN_ENV__"

# Baked at generation: what this server may touch. api_overview returns it
# so an agent can discover its scope before calling anything else.
RESOURCES = __RESOURCES_JSON__

# Baked JSON-Schema tool definitions served by tools/list.
TOOLS = __TOOLS_JSON__


def _token():
    return os.environ.get(DEFAULT_TOKEN_ENV, "")


def _call(method, path, body=None):
    """One API call. Returns parsed JSON; raises RuntimeError on HTTP errors."""
    url = API_HOST + path
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Authorization", "Token " + _token())
    if data is not None:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read()
    except urllib.error.HTTPError as exc:
        raise RuntimeError("HTTP %s from %s: %s" % (exc.code, path,
                                                    exc.read().decode("utf-8", "replace")))
    except urllib.error.URLError as exc:
        raise RuntimeError("cannot reach %s: %s" % (url, exc.reason))
    if not raw:
        return {}
    return json.loads(raw.decode("utf-8"))


def _resource_tool(name, args):
    """Dispatch one <resource>_<action> tool against its baked path spec."""
    resource, _, action = name.rpartition("_")
    spec = next((r for r in RESOURCES if r["name"] == resource), None)
    if spec is None:
        raise KeyError(name)
    # Detail paths were written with {id} by the schema generator; fill it
    # from the tool arguments (quoted — ids may contain odd characters).
    detail = spec["detail_path"].replace("{id}", urllib.parse.quote(str(args["id"]), safe="")) \\
        if spec["detail_path"] else None
    if action == "list":
        params = {k: str(args[k]) for k in ("page", "page_size") if k in args}
        qs = ("?" + urllib.parse.urlencode(params)) if params else ""
        return _call("GET", spec["list_path"] + qs)
    if action == "retrieve":
        return _call("GET", detail)
    if action == "create":
        return _call("POST", spec["list_path"], args["data"])
    if action == "update":
        return _call("PATCH", detail, args["data"])
    if action == "destroy":
        return _call("DELETE", detail)
    raise KeyError(name)


def _tool_call(name, args):
    """Run one tool; HTTP/tool failures become MCP isError results."""
    if name == "api_overview":
        return {"resources": RESOURCES,
                "hint": "tools are <resource>_<list|retrieve|create|update|destroy>"}
    if name == "branding_get":
        return _call("GET", API_HOST + "/admineverywhere/branding/")
    if name == "branding_set":
        return _call("PUT", API_HOST + "/admineverywhere/branding/", args["data"])
    return _resource_tool(name, args)


def _respond(msg_id, result):
    _write({"jsonrpc": "2.0", "id": msg_id, "result": result})


def _fail(msg_id, code, message):
    _write({"jsonrpc": "2.0", "id": msg_id,
            "error": {"code": code, "message": message}})


def _write(payload):
    sys.stdout.write(json.dumps(payload) + "\\n")
    sys.stdout.flush()


def _dispatch(method, params):
    """Returns (result, error_code, error_message) for one request."""
    if method == "initialize":
        return {"protocolVersion": PROTOCOL_VERSION,
                "capabilities": {"tools": {"listChanged": False}},
                "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION}}, None, None
    if method == "tools/list":
        return {"tools": TOOLS}, None, None
    if method == "ping":
        return {}, None, None
    if method == "tools/call":
        name = params.get("name", "")
        try:
            tool = next((t for t in TOOLS if t["name"] == name), None)
        except AttributeError:
            tool = None
        if tool is None:
            return None, -32602, "unknown tool: %s" % name
        try:
            return {"content": [{"type": "text",
                                 "text": json.dumps(_tool_call(name, params.get("arguments") or {}))}],
                    "isError": False}, None, None
        except KeyError as exc:
            return {"content": [{"type": "text",
                                 "text": "missing argument: %s" % exc}],
                    "isError": True}, None, None
        except RuntimeError as exc:
            return {"content": [{"type": "text", "text": str(exc)}],
                    "isError": True}, None, None
    return None, -32601, "method not found: %s" % method


def main():
    for raw in sys.stdin:
        raw = raw.strip()
        if not raw:
            continue
        try:
            msg = json.loads(raw)
        except ValueError as exc:
            _fail(None, -32700, "parse error: %s" % exc)
            continue
        if not isinstance(msg, dict) or "method" not in msg:
            continue
        # Notifications (no id) never get a response per JSON-RPC 2.0.
        if "id" not in msg:
            continue
        result, code, message = _dispatch(msg["method"], msg.get("params") or {})
        if code is None:
            _respond(msg["id"], result)
        else:
            _fail(msg["id"], code, message)


if __name__ == "__main__":
    main()
'''


def render_server(tools: list, resources: list, api_host: str, server_name: str,
                  token_env: str, version: str = "0.0.0") -> str:
    """Render the standalone MCP server. Pure string work — deterministic."""
    # RESOURCES is a Python literal (repr): booleans must read True/False,
    # not JSON true/false — the generated file is executed, not fetched.
    # TOOLS is plain JSON text: it is served verbatim by tools/list and
    # contains only strings/ints, so it is valid Python too.
    return (_TEMPLATE
            .replace("__RESOURCES_JSON__", repr(resources))
            .replace("__TOOLS_JSON__", json.dumps(tools, indent=4))
            .replace("__API_HOST__", api_host)
            .replace("__SERVER_NAME__", server_name)
            .replace("__TOKEN_ENV__", token_env)
            .replace("__VERSION__", version)
            .replace("__PROTOCOL__", "2024-11-05"))
