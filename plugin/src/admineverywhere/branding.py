"""Branding engine — pure functions, no Django, fully unit-tested.

The promise: `build_admin --brand path/brand.json` rebrands the whole app
in <30s. Everything visual in the thin client reads CSS variables
(--brand-*) emitted here, so this is the ONLY file that decides what the
app looks like.

Public API (imported by the management commands):
    load_brand(path) -> dict
    validate_brand(brand) -> list[str]      # empty list = valid
    render_css(brand) -> str
    render_brand_gen(brand, config) -> str  # the inlined src/lib/brand.gen.ts
    stamp_index_html(html, brand) -> str    # vite index.html title/favicon
    brand_slug(app_name) -> str             # "Freshorama Admin" -> "freshorama-admin"
    inject_brand(app_dir, brand_path, api_host=None) -> dict
    normalize_api_host(api_host) -> str         # canonical https origin
    substitute_api_host(conf, api_host) -> str | None   # origin or no-op

Security posture (P0): brand.json is UNTRUSTED input. validate_brand
enforces a closed schema (unknown keys/types/values rejected with clear
errors) and inject_brand jails every read and write with realpath()+
commonpath() so "../" chains, absolute-path injection and symlink escapes
cannot leave the brand or app directories.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path, PurePosixPath
from urllib.request import Request, urlopen  # noqa: F401 (dump_schema monkeypatches urlopen)

HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")
RADIUS_RE = re.compile(r"^\d+(\.\d+)?(px|rem|em)$")
# appName goes into window titles / file paths downstream: keep it boring
SAFE_NAME_RE = re.compile(r"^[^/\\<>:\"|?*\x00-\x1f]{1,120}$")

REQUIRED_KEYS = ["appName", "colors", "radius", "font"]
REQUIRED_COLORS = ["primary", "accent", "bg", "surface", "text"]

# Font names are interpolated into a URL + CSS string: strip anything
# that could break out of the quotes/url.
SAFE_FONT_RE = re.compile(r"^[A-Za-z0-9 ]{1,60}$")

# The shipped tauri.conf.json carries this placeholder in connect-src;
# build_admin --api-host replaces it with the deployed origin at build
# time. Substitution is build-scoped: the committed conf never names a
# real host, and nothing else may edit the CSP.
API_HOST_PLACEHOLDER = "https://API_HOST"

# Canonical shape of an allowed API origin: https + dotted DNS name
# (labels of letters/digits/hyphens) + optional port. Enforced on top of
# explicit localhost/loopback rejection below — defense in depth, since
# this string goes straight into the production CSP.
API_HOST_RE = re.compile(
    r"^https://[a-z0-9]([a-z0-9-]*[a-z0-9])?"
    r"(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+"
    r"(:\d{1,5})?$"
)

# P0: brand.json is untrusted input (shared/downloaded/dropped in) — the
# schema is CLOSED. Every key must be known and correctly typed; anything
# else is a config error and must fail loudly, not be silently ignored.
ALLOWED_KEYS = frozenset(REQUIRED_KEYS + ["tagline", "logo", "favicon",
                                          "icon", "loaderVideo"])
ALLOWED_COLOR_KEYS = frozenset(REQUIRED_COLORS)
TAGLINE_MAX = 140      # tagline is UI chrome, not a paragraph
ASSET_PATH_MAX = 200   # logo/favicon live next to brand.json in the repo

# Optional build-time asset keys (deep branding):
#   icon        -> launcher/installer icon; feeds `npm run tauri icon`, PNG only
#   loaderVideo -> the intro clip that IS the splash loader; browser codecs
#                  only, and capped so a brand.json cannot smuggle a movie in
ICON_EXTS = frozenset({".png"})
LOADER_VIDEO_EXTS = frozenset({".mp4", ".webm"})
LOADER_VIDEO_MAX_BYTES = 8 * 1024 * 1024

# Header stamped onto every generated src/lib/brand.gen.ts (and public CSS).
GEN_HEADER = """/* GENERATED by admineverywhere build_admin — do not edit by hand.
 * Regenerate with: python manage.py build_admin --brand <brand.json> */
"""

# index.html identity stamp (same build-time treatment as tauri.conf.json's
# window title): the dist/ bundle ships the repo's index.html verbatim, so
# without this a branded build presents the stock tab title/favicon until
# the SPA's JS boots and patches the DOM.
HEAD_OPEN_RE = re.compile(r"<head\b[^>]*>", re.IGNORECASE)
TITLE_RE = re.compile(r"<title\b[^>]*>.*?</title\s*>", re.IGNORECASE | re.DOTALL)
FAVICON_LINK_RE = re.compile(
    r"<link\b[^>]*\brel=[\"'](shortcut )?icon[\"'][^>]*>", re.IGNORECASE
)


def load_brand(path: str | Path) -> dict:
    """Read brand.json; raise FileNotFoundError / ValueError with clear text."""
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(f"brand file not found: {p}")
    try:
        brand = json.loads(p.read_text())
    except json.JSONDecodeError as exc:
        raise ValueError(f"invalid JSON in {p}: {exc}") from exc
    if not isinstance(brand, dict):
        raise ValueError(f"{p} must contain a JSON object")
    return brand


def _escapes_brand_folder(rel: str) -> bool:
    """True when an asset path is absolute or climbs out of the brand folder.

    PurePosixPath judges the JSON spelling ('/'-separated), not the host OS;
    backslashes are rejected outright — Windows-style traversal has no
    legitimate use in a brand.json.
    """
    p = PurePosixPath(rel)
    return p.is_absolute() or ".." in p.parts or "\\" in rel


# ---------------------------------------------------------------------------
# P0: path jail. Every file read/write in this module resolves its target
# through realpath() (symlinks included) and verifies with commonpath()
# that it stays inside the intended directory. Blocks:
#   - "../" chains hidden in brand.json asset paths
#   - absolute-path injection ("logo": "/etc/passwd")
#   - symlink escapes (a planted public/brand.css -> ~/.bashrc would
#     otherwise be clobbered through the link; an asset symlinking to
#     files outside the brand folder would otherwise be exfiltrated)
# Callers MUST use the returned (resolved) path for the actual operation,
# so what was validated is exactly what gets read/written.
# ---------------------------------------------------------------------------

def _jailed(base: str | Path, rel: str | Path, what: str) -> Path:
    """Resolve ``base / rel`` and guarantee the result stays under ``base``.

    Raises ValueError with a clear message on any escape. ``rel`` may be
    absolute — it only survives if it already resolves inside ``base``.
    """
    base_real = Path(os.path.realpath(base))
    candidate = Path(rel)
    joined = candidate if candidate.is_absolute() else base_real / candidate
    target_real = Path(os.path.realpath(joined))
    try:
        inside = os.path.commonpath([str(base_real), str(target_real)]) == str(base_real)
    except ValueError:  # mixed forms / different drives — treat as escape
        inside = False
    if not inside or target_real == base_real:
        raise ValueError(
            f"{what}: path escapes {base_real} ({str(rel)!r}) — "
            "refusing to read/write outside the intended directory"
        )
    return target_real


def validate_brand(brand: dict) -> list[str]:
    """Collect ALL problems (never early-return) so clients fix in one pass."""
    errors: list[str] = []

    app_name = brand.get("appName")
    if not isinstance(app_name, str) or not app_name.strip():
        errors.append("appName: must be a non-empty string")
    elif not SAFE_NAME_RE.match(app_name.strip()):
        errors.append("appName: contains characters not safe for window titles")

    # P0: closed schema — unknown keys are typos/config drift; fail loudly
    # instead of silently ignoring them.
    unknown = sorted(set(brand) - ALLOWED_KEYS)
    if unknown:
        errors.append(
            f"unknown keys: {', '.join(unknown)} (allowed: {', '.join(sorted(ALLOWED_KEYS))})"
        )

    # tagline: optional, but must be a short sane string when present.
    tagline = brand.get("tagline")
    if tagline is not None:
        if not isinstance(tagline, str) or not tagline.strip():
            errors.append(f"tagline: must be a non-empty string (got {tagline!r})")
        elif len(tagline) > TAGLINE_MAX:
            errors.append(f"tagline: longer than {TAGLINE_MAX} characters (got {len(tagline)})")

    # logo/favicon/icon/loaderVideo: relative asset paths only. Absolute
    # paths and ".." components are rejected here, and re-checked with
    # realpath at copy time (see _jailed) — belt and suspenders.
    for key in ("logo", "favicon", "icon", "loaderVideo"):
        rel = brand.get(key)
        if rel is None:
            continue
        if not isinstance(rel, str) or not rel.strip():
            errors.append(f"{key}: must be a relative path string like 'assets/logo.svg' (got {rel!r})")
        elif len(rel) > ASSET_PATH_MAX:
            errors.append(f"{key}: path longer than {ASSET_PATH_MAX} characters")
        elif _escapes_brand_folder(rel):
            errors.append(f"{key}: must stay inside the brand folder — no absolute paths or '..' (got {rel!r})")

    # The new asset keys are extension-locked on top of path safety: icon
    # feeds `tauri icon` (png in, all platforms out), loaderVideo rides the
    # browser's <video> codecs. Unknown extensions are drift — reject.
    for key, exts in (("icon", ICON_EXTS), ("loaderVideo", LOADER_VIDEO_EXTS)):
        rel = brand.get(key)
        if not isinstance(rel, str) or not rel:
            continue
        if PurePosixPath(rel).suffix.lower() not in exts:
            errors.append(
                f"{key}: extension must be one of {', '.join(sorted(exts))} (got {rel!r})")

    colors = brand.get("colors")
    if not isinstance(colors, dict):
        errors.append("colors: must be an object")
        colors = {}
    else:
        # P0: closed schema for colors too — unknown keys are drift.
        unknown_colors = sorted(set(colors) - ALLOWED_COLOR_KEYS)
        if unknown_colors:
            errors.append(
                f"colors: unknown keys {', '.join(unknown_colors)} "
                f"(allowed: {', '.join(sorted(ALLOWED_COLOR_KEYS))})"
            )
    for key in REQUIRED_COLORS:
        val = colors.get(key)
        if not isinstance(val, str) or not HEX_RE.match(val):
            errors.append(f"colors.{key}: must be a 6-digit hex color like #7c3aed (got {val!r})")

    radius = brand.get("radius")
    if not isinstance(radius, str) or not RADIUS_RE.match(radius):
        errors.append(f"radius: must be a CSS length like '0.75rem' or '12px' (got {radius!r})")

    font = brand.get("font")
    if not isinstance(font, str) or not SAFE_FONT_RE.match(font.strip()):
        errors.append(f"font: must be a plain Google Font name like 'Inter' (got {font!r})")

    return errors


def stamp_index_html(html: str, brand: dict) -> str:
    """Rewrite the vite index.html identity for a brand (title + favicon).

    Pure + idempotent. The title becomes appName; with a brand favicon the
    <link rel=icon> href is set to the stamped public/-root basename
    ("assets/icon.png" -> "/icon.png"), injecting a link when the document
    has none. Without a brand favicon the existing links are left alone —
    the title is always stamped.
    """
    app_name = brand["appName"]
    if TITLE_RE.search(html):
        html = TITLE_RE.sub(f"<title>{app_name}</title>", html, count=1)
    else:
        head = HEAD_OPEN_RE.search(html)
        if head:
            html = (
                html[: head.end()]
                + f"\n    <title>{app_name}</title>"
                + html[head.end():]
            )

    favicon = brand.get("favicon")
    if favicon:
        link = f'<link rel="icon" href="/{PurePosixPath(favicon).name}" />'
        if FAVICON_LINK_RE.search(html):
            html = FAVICON_LINK_RE.sub(link, html)
        else:
            html = html.replace("</head>", f"    {link}\n  </head>", 1)
    return html


def brand_slug(app_name: str) -> str:
    """appName -> filename-safe slug ("Freshorama Admin" -> "freshorama-admin").

    Lowercased, every non-alphanumeric run collapsed to one "-", trimmed.
    The generator outputs (<slug>-mcp-server.py, <slug>-admin.el) are named
    from it, so the result must be boring on every filesystem.
    """
    slug = re.sub(r"[^a-z0-9]+", "-", (app_name or "").lower()).strip("-")
    return slug or "admineverywhere"


def render_brand_gen(brand: dict, config: dict) -> str:
    """brand + config -> the TypeScript module the SPA imports at boot.

    src/lib/brand.gen.ts INLINES the identity into the bundle, so a Tauri
    Android boot never depends on fetching public/*.json through the asset
    protocol (which serves SPA-fallback HTML for those paths — the JSON
    parse died and the app silently booted stock). Mirrors render_css():
    pure, deterministic, fully unit-tested.
    """
    return (
        GEN_HEADER
        + 'import type { Brand, AppConfig } from "./stores";\n'
        + f"export const BUNDLED_BRAND: Brand = {json.dumps(brand, indent=2)};\n"
        + f"export const BUNDLED_CONFIG: AppConfig = {json.dumps(config, indent=2)};\n"
    )


def render_css(brand: dict) -> str:
    """brand.json -> CSS custom properties on :root (+ Google Font import)."""
    colors = brand["colors"]
    font = brand["font"].strip()
    import_name = font.replace(" ", "+")
    return f"""/* GENERATED by admineverywhere build_admin — do not edit by hand.
 * Regenerate with: python manage.py build_admin --brand <brand.json>
 */
@import url('https://fonts.googleapis.com/css2?family={import_name}:wght@400;500;600;700&display=swap');

:root {{
  --brand-primary: {colors['primary']};
  --brand-accent: {colors['accent']};
  --brand-bg: {colors['bg']};
  --brand-surface: {colors['surface']};
  --brand-text: {colors['text']};
  --brand-radius: {brand['radius']};
  --brand-font: '{font}', ui-sans-serif, system-ui, sans-serif;
}}
"""


# ---------------------------------------------------------------------------
# Production CSP: the shipped tauri.conf.json carries connect-src
# 'self' https://API_HOST. build_admin --api-host replaces the placeholder
# with the deployed origin at build time — the ONLY sanctioned way a real
# host enters the CSP (validated below: https only, dotted DNS, no
# localhost/loopback, no wildcards, no paths/userinfo).
#
# WHY img-src/font-src/style-src are not 'self'-only (BRE Finding 2): two
# product promises need third-party origins, and a self-only policy would
# break both silently — the app just falls back to no logo / system font:
#   - brand.json names a webfont; render_css() (and the client's
#     brandToCss()) emit @import url('https://fonts.googleapis.com/css2?..'),
#     which is gated by STYLE-src (the @import fetch), then the .woff2 files
#     load from fonts.gstatic.com under FONT-src. Both origins are required.
#   - a brand logo may be a hosted URL (not only a data: upload), so IMG-src
#     needs https: — and data: stays for the runtime branding API.
# script-src 'self' is untouched: execution stays locked, only egress for
# these two known brand origins widens. Pinned by TestProdCspBrandOrigins.
# ---------------------------------------------------------------------------

def normalize_api_host(api_host: str) -> str:
    """Validate + normalize the deployed API origin for the production CSP.

    Accepts 'admin.example.com' or 'https://admin.example.com[:port]';
    returns the canonical origin (https scheme, lowercased, no trailing
    slash). Anything that must never ship in a production CSP fails
    loudly: plain http, localhost/loopback, wildcards, paths, userinfo,
    bare single-label hosts.
    """
    if not isinstance(api_host, str) or not api_host.strip():
        raise ValueError(
            "api-host: must be a non-empty origin like 'https://admin.example.com'"
        )
    origin = api_host.strip().rstrip("/")
    if "://" not in origin:
        origin = "https://" + origin
    scheme, _, rest = origin.partition("://")
    if scheme.lower() != "https":
        raise ValueError(f"api-host: only https origins are allowed (got {api_host!r})")
    if "*" in rest:
        raise ValueError(
            f"api-host: wildcard origins can never ship in the CSP (got {api_host!r})"
        )
    origin = (scheme.lower() + "://" + rest).lower()
    if not API_HOST_RE.match(origin):
        raise ValueError(
            "api-host: must be a dotted DNS origin like 'https://admin.example.com' "
            f"(got {api_host!r})"
        )
    host = origin[len("https://"):].split(":", 1)[0]
    if host == "localhost" or host.endswith(".localhost") or host in {"127.0.0.1", "0.0.0.0"}:
        raise ValueError(
            f"api-host: localhost/loopback can never ship in the CSP (got {api_host!r})"
        )
    return origin


def substitute_api_host(conf: dict, api_host: str) -> str | None:
    """Substitute the CSP API_HOST placeholder in a parsed tauri.conf dict.

    Mutates conf["app"]["security"]["csp"] in place. Returns the origin
    that was substituted in, or None when the CSP already carries it
    (idempotent re-runs of build_admin). Any drift fails loudly instead of
    shipping a config the client cannot reach its API through: a missing
    CSP, or a CSP with neither the placeholder nor the requested origin.
    """
    origin = normalize_api_host(api_host)
    security = conf.get("app", {}).get("security", {})
    csp = security.get("csp") if isinstance(security, dict) else None
    if not isinstance(csp, str) or not csp:
        raise ValueError(
            "tauri.conf.json: app.security.csp missing — cannot substitute api-host"
        )
    if API_HOST_PLACEHOLDER in csp:
        security["csp"] = csp.replace(API_HOST_PLACEHOLDER, origin)
        return origin
    if origin in csp:
        return None  # same origin already substituted — nothing to do
    raise ValueError(
        "tauri.conf.json: csp has neither the API_HOST placeholder nor "
        f"{origin!r} — refusing to guess (config drift)"
    )


def _bundled_config(app: Path, api_host: str | None) -> dict:
    """The config object inlined into brand.gen.ts (see render_brand_gen).

    With --api-host the validated origin wins as apiUrl. Without it, a
    pre-existing public/config.json carries the deployed URLs across a
    restamp (dev trees point at localhost:8000); no file, empty origin —
    the login screen and --api-host are the sanctioned ways to name one.
    authPath/schemaPath ride along from that file so a customized backend
    shape survives stamping, else the documented defaults.
    """
    defaults = {"apiUrl": "", "authPath": "/api/auth/token/", "schemaPath": "/api/schema/"}
    existing: dict = {}
    config_json = app / "public" / "config.json"
    if config_json.is_file():
        try:
            parsed = json.loads(_jailed(app / "public", "config.json", "config.json").read_text())
            if isinstance(parsed, dict):
                existing = parsed
        except (json.JSONDecodeError, OSError):
            existing = {}  # a broken config.json must not break the stamp

    def pick(key: str) -> str:
        val = existing.get(key)
        return val if isinstance(val, str) else defaults[key]

    cfg = {"apiUrl": pick("apiUrl"), "authPath": pick("authPath"), "schemaPath": pick("schemaPath")}
    if api_host is not None:
        cfg["apiUrl"] = normalize_api_host(api_host)
    return cfg


def _tauri_icon(app_dir: Path, icon_png: Path) -> None:
    """Regenerate every platform icon from a brand png (`npm run tauri icon`).

    Same style as build_admin._npm (npm subprocess, cwd=app). Raises on ANY
    failure — inject_brand catches and records a skip line instead: hosts
    without npm/@tauri-apps/cli, or with an unparsable png, must still be
    able to stamp the rest of the brand.

    The CLI arg must be app-RELATIVE: build_admin --app app runs from the
    repo root, but the staged png arrives as an absolute jailed path, and
    Path.relative_to(app_dir) raised for a relative app_dir — `tauri icon`
    was silently skipped on exactly the documented invocation.
    """
    rel = os.path.relpath(icon_png, app_dir)
    subprocess.run(
        ["npm", "run", "tauri", "icon", rel],
        cwd=app_dir,
        check=True,
        capture_output=True,
    )


def inject_brand(app_dir: str | Path, brand_path: str | Path,
                 api_host: str | None = None) -> dict:
    """Apply a brand to the thin-client app directory.

    Writes:  public/brand.css, public/brand.json (normalized asset paths),
             src/lib/brand.gen.ts (brand + config INLINED into the bundle),
             index.html (brand tab title + favicon link)
    Copies:  logo + favicon + loaderVideo -> public/, icon -> public/ (then
             `npm run tauri icon` regenerates the platform icons, best effort)
    Patches: src-tauri/tauri.conf.json (productName, window title) if present
    CSP:     with api_host, substitutes the API_HOST placeholder in
             app.security.csp (see substitute_api_host; validated + loud)

    P0: brand.json is untrusted — every source and destination below goes
    through _jailed() (realpath + commonpath), so neither hostile asset
    references nor symlinks planted inside the app can read or write
    outside the intended directories.

    Returns a summary {"written": [...], "copied": [...], "patched": [...],
    "skipped": [...], "csp_api_host": <origin or None>} that the
    build_admin command prints.
    """
    # Fail fast on a bad --api-host BEFORE any file is touched (the
    # substitution itself happens at the tauri.conf patching step below).
    if api_host is not None:
        normalize_api_host(api_host)

    app = Path(app_dir)
    brand_file = Path(brand_path)
    brand = load_brand(brand_file)
    errors = validate_brand(brand)
    if errors:
        raise ValueError("invalid brand.json:\n  - " + "\n  - ".join(errors))

    pub = app / "public"
    pub.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    copied: list[str] = []
    skipped: list[str] = []

    # 1. CSS variables. Jailed: a pre-existing public/brand.css symlink
    #    pointing outside the app must be refused, not written through.
    css_path = _jailed(pub, "brand.css", "brand.css")
    css_path.write_text(render_css(brand))
    written.append(str((pub / "brand.css").relative_to(app)))

    # 2. Assets (paths are relative to the brand.json's own folder).
    #    Source is jailed to the brand folder (blocks ../ chains,
    #    absolute-path injection and symlinked assets reaching outside —
    #    an untrusted brand.json must not exfiltrate arbitrary files into
    #    the shipped app); destination is jailed to public/.
    out_brand = dict(brand)
    for key in ("logo", "favicon", "loaderVideo"):
        rel = brand.get(key)
        if not rel:
            continue
        src = _jailed(brand_file.parent, rel, f"{key} source")
        if not src.is_file():
            raise FileNotFoundError(f"{key} file not found: {src}")
        if key == "loaderVideo" and src.stat().st_size > LOADER_VIDEO_MAX_BYTES:
            raise ValueError(
                f"loaderVideo: larger than {LOADER_VIDEO_MAX_BYTES} bytes "
                f"(got {src.stat().st_size}) — the intro loader must stay small"
            )
        dest_name = Path(rel).name
        dest = _jailed(pub, dest_name, f"{key} destination")
        shutil.copy2(src, dest)
        copied.append(str((pub / dest_name).relative_to(app)))
        out_brand[key] = dest_name  # normalized: served from public/ root

    # The icon is build-time-only (launcher/installer pixels): consumed by
    # `tauri icon` below, never shipped to the client brand.
    out_brand.pop("icon", None)

    # 3. brand.json for runtime reads (appName, tagline, logo path, font)
    brand_json_path = _jailed(pub, "brand.json", "brand.json")
    brand_json_path.write_text(json.dumps(out_brand, indent=2) + "\n")
    written.append(str((pub / "brand.json").relative_to(app)))

    # 3b. The bundle-time identity: src/lib/brand.gen.ts inlines the brand
    #     + config so the SPA boots branded WITHOUT fetching public/*.json
    #     at runtime (on Tauri Android the asset protocol answers those
    #     paths with the SPA-fallback HTML, the JSON parse died, and the
    #     app booted stock: stock splash, empty apiUrl, stock identity).
    #     A committed stock default keeps the dev tree compiling before any
    #     stamping has run.
    gen_rel = "src/lib/brand.gen.ts"
    (app / "src" / "lib").mkdir(parents=True, exist_ok=True)
    gen_path = _jailed(app, gen_rel, "brand.gen.ts")
    gen_path.write_text(render_brand_gen(out_brand, _bundled_config(app, api_host)))
    written.append(str((app / gen_rel).relative_to(app)))

    # 3c. The vite index.html identity: dist/ ships this file verbatim, so
    #     without the stamp a branded build presents the stock tab title
    #     ("Admineverywhere") and favicon until the SPA's JS boots — QA 5-a
    #     D2. Same build-time treatment as the tauri.conf.json window title
    #     below; jailed like every other write, skipped when absent.
    index_html = app / "index.html"
    if index_html.is_file():
        target = _jailed(app, "index.html", "index.html")
        target.write_text(stamp_index_html(target.read_text(), brand))
        written.append(str(index_html.relative_to(app)))

    # 4. Patch Tauri config (window title, product name) — best effort.
    #    Jailed like every other write: a symlinked tauri.conf.json that
    #    resolves outside src-tauri/ is refused instead of patched.
    #
    #    CSP substitution point: the shipped app.security.csp carries
    #    connect-src 'self' https://API_HOST. When --api-host is given,
    #    substitute_api_host replaces the placeholder with the deployed
    #    origin here (validated: https, dotted DNS, no localhost, no
    #    wildcards; drift raises). Without --api-host the placeholder
    #    stays — dev/CI builds keep a host-free CSP.
    patched: list[str] = []
    substituted: str | None = None
    tauri_conf = app / "src-tauri" / "tauri.conf.json"

    # 4a. Brand launcher/installer icon: stage the png into public/ (same
    #     jail as the favicon) and let `tauri icon` derive every platform
    #     icon set from it. Best effort BY DESIGN — recorded as a skip line,
    #     never raised: builds on hosts without the tauri CLI keep working.
    icon_rel = brand.get("icon")
    if icon_rel:
        if not tauri_conf.is_file():
            skipped.append("tauri icon (no src-tauri/tauri.conf.json to re-icon)")
        else:
            try:
                src = _jailed(brand_file.parent, icon_rel, "icon source")
                if not src.is_file():
                    raise FileNotFoundError(f"icon file not found: {src}")
                dest = _jailed(pub, "icon-brand.png", "icon destination")
                shutil.copy2(src, dest)
                copied.append(str((pub / "icon-brand.png").relative_to(app)))
                _tauri_icon(app, dest)
            except (OSError, ValueError, subprocess.SubprocessError) as exc:
                skipped.append(f"tauri icon ({exc})")

    # 4. Patch Tauri config (window title, product name) — best effort.
    if tauri_conf.is_file():
        conf_target = _jailed(app / "src-tauri", "tauri.conf.json", "tauri.conf.json")
        conf = json.loads(conf_target.read_text())
        conf["productName"] = brand["appName"]
        windows = conf.get("app", {}).get("windows", [])
        if windows:
            windows[0]["title"] = brand["appName"]
        if api_host is not None:
            substituted = substitute_api_host(conf, api_host)
        conf_target.write_text(json.dumps(conf, indent=2) + "\n")
        patched.append(str(tauri_conf.relative_to(app)))

    return {"written": written, "copied": copied, "patched": patched,
            "skipped": skipped, "csp_api_host": substituted}
