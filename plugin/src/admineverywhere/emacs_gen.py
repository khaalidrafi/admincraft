"""Emacs package renderer — emits the Org-powered admin client as one string.

The generated artifact is a single-file Emacs package. Design rules
come from the Owner's global AGENTS.md: Org first (records are Org
headlines with properties drawers, TODO states write back to the API),
built for LARGE data (explicit pagination, never fetching everything),
and AI via plain text (the record's Org subtree becomes the model
context; gptel is used when installed, an OpenAI-compatible endpoint
otherwise). Conservative elisp only: url-retrieve-synchronously,
json.el, auth-source, define-derived-mode — nothing that needs a newer
Emacs than 27.1. No emacs is available in the build sandbox, so the
generator sticks to textbook APIs and the byte-compile leg of the test
suite runs wherever emacs exists.
"""

from __future__ import annotations


def _el_str(value: str) -> str:
    """Escape a Python string into an elisp double-quoted string body."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _el_resources(resources: list) -> str:
    """Bake the resource roster as an elisp alist.

    Each entry: (NAME LIST-PATH DETAIL-PATH CREATE UPDATE DESTROY) with
    elisp booleans; DETAIL-PATH is nil for collection-only resources.
    """
    rows = []
    for r in resources:
        rows.append("({} {} {} {} {} {})".format(
            _el_str(r["name"]), _el_str(r["list_path"]),
            _el_str(r["detail_path"]) if r["detail_path"] else "nil",
            "t" if r["create"] else "nil",
            "t" if r["update"] else "nil",
            "t" if r["destroy"] else "nil"))
    return " ".join(rows)


def _el_roster(resources: list) -> str:
    """One-line human roster used in the docstring and AI context."""
    return ", ".join(r["name"] for r in resources)


_TEMPLATE = ''';;; __PACKAGE__.el --- Org-powered admin client -*- lexical-binding: t; -*-

;; Copyright (C) __YEAR__ the admineverywhere project
;; Author: admineverywhere build_emacs <admineverywhere@invalid>
;; Version: __VERSION__
;; Package-Requires: ((emacs "27.1") (org "9.3"))
;; Keywords: org, admin, todo, ai
;; URL: __API_HOST__

;;; Commentary:

;; Org-powered admin client for the __API_HOST__ API.  Generated code:
;; every regeneration is deterministic and safe to re-run.
;;
;; Resources baked in at generation time: __ROSTER__.
;;
;; What you get, in Org, on plain text:
;;   M-x aw-open     - a resource as an Org buffer: one headline per
;;                     record, fields as a properties drawer.  Built for
;;                     LARGE data: pagination with +/- (aw-page-size at
;;                     a time), never the whole table.
;;   M-x aw-todos    - open records as Org TODO items; toggling the TODO
;;                     state PATCHes the status field back to the API.
;;   Editing         - edit a record's properties drawer, then M-x
;;                     aw-save (or \\<aw-mode-map>\\[aw-save]) to PATCH it.
;;   M-x aw-ask      - plain-text AI: the current Org subtree + the
;;                     resource roster become the context.  Uses gptel
;;                     when installed (aw-use-gptel), otherwise any
;;                     OpenAI-compatible endpoint (aw-ai-base-url).
;;
;; Setup (global convention: use-package):
;;
;;   (use-package freshorama-admin
;;     :load-path "~/src/freshorama-admin"
;;     :custom
;;     (aw-api-host "__API_HOST__")
;;     (aw-page-size 50)
;;     :bind (("C-c A" . aw-open)))
;;
;; Auth: API token from auth-source (host = aw-api-host) or the
;; ADMINEVERYWHERE_API_TOKEN env var.  Nothing is hardcoded.

;;; Code:

(require 'org)
(require 'json)
(require 'url)
(require 'auth-source)
(require 'seq)
(require 'cl-lib)
(require 'subr-x)

(defgroup freshorama nil
  "Org admin client for __API_HOST__."
  :prefix "aw-" :group 'applications)

(defcustom aw-api-host "__API_HOST__"
  "Admin API origin (https).  Regenerated by build_emacs."
  :type 'string :group 'freshorama)

(defcustom aw-page-size 50
  "Records fetched per page.  Large-data guard: aw buffers page,
they never fetch a whole table."
  :type 'integer :group 'freshorama)

(defcustom aw-todo-resource "__FIRST_RESOURCE__"
  "Resource whose open records become Org TODO items in `aw-todos'."
  :type 'string :group 'freshorama)

(defcustom aw-status-field "status"
  "Record field the TODO state maps to."
  :type 'string :group 'freshorama)

(defcustom aw-open-statuses '("open" "pending" "in_progress")
  "Status values rendered as TODO; everything else is skipped."
  :type '(repeat string) :group 'freshorama)

(defcustom aw-status-map '((TODO . "open") (DONE . "done"))
  "Org TODO keyword -> API status value for write-back."
  :type '(alist :key-type symbol :value-type string) :group 'freshorama)

(defcustom aw-use-gptel t
  "When gptel is installed, use it for `aw-ask' instead of the raw
OpenAI-compatible endpoint."
  :type 'boolean :group 'freshorama)

(defcustom aw-ai-base-url "https://api.openai.com/v1"
  "OpenAI-compatible endpoint used by `aw-ask' without gptel."
  :type 'string :group 'freshorama)

(defcustom aw-ai-model "gpt-4o-mini"
  "Model name for the raw endpoint path."
  :type 'string :group 'freshorama)

;; --- baked resource roster -------------------------------------------
;; (NAME LIST-PATH DETAIL-PATH CREATE UPDATE DESTROY)
(defconst aw--resources
  '__RESOURCES__)

;; Buffer-local render state: which resource/page this Org buffer shows.
;; Deliberately not Org properties — render state is not record data.
(defvar-local aw--current-resource nil)
(defvar-local aw--current-page 1)

;; Re-entrancy guard: the TODO-state hook must not PATCH while the
;; renderer is writing TODO headlines into a fresh buffer.
(defvar-local aw--render-in-progress nil)

(defun aw--resource (name)
  "Return the roster entry for resource NAME."
  (or (seq-find (lambda (r) (string= (nth 0 r) name)) aw--resources)
      (user-error "AW: unknown resource %s" name)))

(defun aw--token ()
  "API token: auth-source first (host = aw-api-host), env var fallback."
  (or (auth-source-pick-first-password :host aw-api-host)
      (getenv "ADMINEVERYWHERE_API_TOKEN")
      (user-error "AW: no API token (auth-source host %s or env ADMINEVERYWHERE_API_TOKEN)" aw-api-host)))

(defun aw--request (method path &optional body)
  "One synchronous API call: METHOD PATH with optional JSON BODY.
Returns the parsed JSON response (arrays as lists), or nil on an
empty body."
  (let* ((url (concat aw-api-host path))
         (url-request-method method)
         (url-request-extra-headers
          `(("Content-Type" . "application/json")
            ("Authorization" . ,(concat "Token " (aw--token)))))
         (url-request-data
          (and body (encode-coding-string (json-encode body) 'utf-8)))
         (buf (url-retrieve-synchronously url)))
    (unless buf (error "AW: cannot reach %s" url))
    (unwind-protect
        (with-current-buffer buf
          (goto-char (point-min))
          ;; url.el speaks HTTP/1.1 but match any version to be honest
          ;; about the status line we were actually served.
          (let ((status-line (buffer-substring
                              (point-min) (progn (end-of-line) (point)))))
            (unless (string-match-p "^HTTP/[0-9.]+ 2" status-line)
              (error "AW: %s" (string-trim status-line))))
          ;; Header/body separator is CRLF per HTTP; search the raw pair.
          (re-search-forward "\\r\\n\\r\\n" nil t)
          (let ((json-array-type 'list)
                (json-object-type 'alist))
            (if (looking-at-p "[[:space:]]*\\\\'")
                nil
              (json-read-from-string
               (decode-coding-string
                (buffer-substring (point) (point-max)) 'utf-8)))))
      (kill-buffer buf))))

(defun aw--page (resource page)
  "Fetch PAGE of RESOURCE (DRF pagination; plain lists pass through).
Returns the list of record alists."
  (let* ((path (nth 1 (aw--resource resource)))
         (resp (aw--request
                "GET" (format "%s?page=%d&page_size=%d" path page aw-page-size))))
    (cond ((listp resp) resp)                       ; non-paginated backend
          ((alist-get 'results resp))               ; PageNumberPagination
          (t nil))))

(defun aw--summary (record)
  "One-line headline text for RECORD: id plus the first text field."
  (let* ((id (alist-get 'id record))
         (field (seq-find
                 (lambda (kv)
                   (and (symbolp (car kv))
                        (not (memq (car kv) '(id pk)))
                        (stringp (cdr kv))))
                 record)))
    (format "%s%s" (or id "?")
            (if field (format " - %s" (cdr field)) ""))))

(defun aw--flat (value)
  "One-line string for a property value (drawers cannot hold newlines)."
  (replace-regexp-in-string "\\n" " " (format "%s" (or value ""))))

(defun aw--insert-record (record)
  "Insert RECORD as an Org headline with a properties drawer."
  (insert "** " (aw--summary record) "\\n")
  (insert "   :PROPERTIES:\\n")
  (dolist (kv record)
    (insert (format "   :%s: %s\\n" (upcase (format "%s" (car kv)))
                    (aw--flat (cdr kv)))))
  (insert "   :END:\\n"))

(defun aw--render (resource page records)
  "Fill the *AW: resource* buffer with one Org headline per record.
Returns the buffer."
  (let ((buf (get-buffer-create (format "*AW: %s*" resource))))
    (with-current-buffer buf
      (let ((inhibit-read-only t))
        (setq aw--render-in-progress t
              aw--current-resource resource
              aw--current-page page)
        (erase-buffer)
        (insert "#+TITLE: " resource " - page " (number-to-string page) "\\n\\n")
        (if records
            (dolist (r records) (aw--insert-record r) (insert "\\n"))
          (insert "No records on this page.\\n"))
        (org-mode)
        (aw-mode)
        (setq aw--render-in-progress nil)
        (goto-char (point-min))))
    buf))

(defun aw--current-resource ()
  "Resource name of the current aw buffer (or ask)."
  (or aw--current-resource
      (completing-read "Resource: "
                       (mapcar (lambda (r) (nth 0 r)) aw--resources))))

(defun aw--refresh ()
  "Re-fetch the current buffer's page."
  (interactive)
  (let ((resource (aw--current-resource))
        (page aw--current-page))
    (pop-to-buffer (aw--render resource page (aw--page resource page)))))

(defun aw--page-next ()
  "Next page of the current resource (large data: never load all)."
  (interactive)
  (let* ((resource (aw--current-resource))
         (page (1+ aw--current-page)))
    (pop-to-buffer (aw--render resource page (aw--page resource page)))))

(defun aw--page-prev ()
  "Previous page of the current resource."
  (interactive)
  (let* ((resource (aw--current-resource))
         (page (max 1 (1- aw--current-page))))
    (pop-to-buffer (aw--render resource page (aw--page resource page)))))

(defun aw-open (resource)
  "Open RESOURCE as a paginated Org buffer."
  (interactive (list (completing-read
                      "Resource: " (mapcar (lambda (r) (nth 0 r)) aw--resources))))
  (pop-to-buffer (aw--render resource 1 (aw--page resource 1))))

(defun aw--record-at-point ()
  "The record id under point (from the properties drawer)."
  (save-excursion
    (org-back-to-heading t)
    (or (org-entry-get (point) "ID")
        (user-error "AW: no record under point"))))

(defun aw--drawer-data ()
  "Properties drawer at point (minus ID) as an alist for PATCH bodies."
  (save-excursion
    (org-back-to-heading t)
    (let ((end (save-excursion (outline-next-heading) (point)))
          data)
      (while (re-search-forward "^   :\\([A-Za-z0-9_-]+\\):[ \\t]*\\(.*\\)$" end t)
        (let ((key (downcase (match-string 1)))
              (val (string-trim (match-string 2))))
          (unless (member key '("id" "pk"))
            (push (cons (intern key) val) data))))
      data)))

(defun aw--detail-path (resource id)
  "Detail URL path for resource ID with {id} filled and quoted."
  (let ((detail (nth 2 (aw--resource resource))))
    (unless detail (user-error "AW: %s has no detail endpoint" resource))
    (replace-regexp-in-string "{id}" (url-hexify-string id) detail)))

(defun aw-save ()
  "PATCH the record under point with its edited properties drawer."
  (interactive)
  (let* ((id (aw--record-at-point))
         (resource (aw--current-resource)))
    (aw--request "PATCH" (aw--detail-path resource id) (aw--drawer-data))
    (message "AW: saved %s %s" resource id)))

(defun aw-delete ()
  "Delete the record under point, after confirmation."
  (interactive)
  (let* ((id (aw--record-at-point))
         (resource (aw--current-resource))
         (spec (aw--resource resource)))
    (unless (nth 5 spec) (user-error "AW: %s cannot be deleted" resource))
    (when (yes-or-no-p (format "Delete %s %s? " resource id))
      (aw--request "DELETE" (aw--detail-path resource id))
      (aw--refresh))))

(defun aw-create (resource)
  "Create a record in RESOURCE from a key:value minibuffer prompt.
Kept deliberately simple for v1: one KEY: VALUE pair per comma."
  (interactive (list (aw--current-resource)))
  (let* ((spec (aw--resource resource))
         (raw (read-string
               (format "Fields for new %s (key: value, comma-separated): "
                       resource))))
    (unless (nth 3 spec) (user-error "AW: %s cannot be created" resource))
    (aw--request "POST" (nth 1 spec) (aw--parse-kv raw))
    (aw--refresh)
    (message "AW: created %s" resource)))

(defun aw--parse-kv (raw)
  "Parse 'a: 1, b: two' into an alist ((a . \"1\") (b . \"two\"))."
  (mapcar (lambda (p)
            (let ((kv (split-string p ":" t "[[:space:]]*")))
              (cons (intern (car kv)) (string-join (cdr kv) ":"))))
          (split-string raw "," t "[[:space:]]*")))

(defun aw--sync-todo ()
  "Write the TODO state of the item under point back to the API."
  ;; Skip while the renderer writes, and only the todos buffer syncs —
  ;; a plain records buffer of another resource must not PATCH.
  (unless (or aw--render-in-progress
              (not (string= (or aw--current-resource "") aw-todo-resource)))
    (ignore-errors
      (let* ((state (org-entry-get (point) "TODO"))
             (status (cdr (assoc (intern state) aw-status-map)))
             (id (org-entry-get (point) "ID")))
        (when (and status id)
          (aw--request "PATCH"
                       (aw--detail-path aw-todo-resource id)
                       (list (cons (intern aw-status-field) status)))
          (message "AW: %s -> %s" id status))))))

(defun aw-todos ()
  "Open records of `aw-todo-resource' as Org TODO items.

Toggle the TODO keyword and the new state PATCHes back (see
`aw-status-map').  Fetches at most 5 pages — large data stays bounded."
  (interactive)
  (let* ((resource aw-todo-resource)
         (records (apply #'append
                         (cl-loop for page from 1 to 5
                                  collect (aw--page resource page))))
         (open (seq-filter
                (lambda (r)
                  (member (aw--flat (cdr (assq (intern aw-status-field) r)))
                          aw-open-statuses))
                records))
         (buf (get-buffer-create (format "*AW: %s TODOs*" resource))))
    (with-current-buffer buf
      (let ((inhibit-read-only t))
        (setq aw--render-in-progress t
              aw--current-resource resource
              aw--current-page 1)
        (erase-buffer)
        (insert "#+TITLE: " resource " - open TODOs\\n\\n")
        (if open
            (dolist (r open)
              (insert "** TODO " (aw--summary r) "\\n")
              (insert "   :PROPERTIES:\\n")
              (insert (format "   :ID: %s\\n" (aw--flat (cdr (assq 'id r)))))
              (insert (format "   :%s: %s\\n" (upcase aw-status-field)
                              (aw--flat (cdr (assq (intern aw-status-field) r)))))
              (insert "   :END:\\n\\n"))
          (insert "Nothing open.\\n"))
        (org-mode)
        (aw-mode)
        (setq aw--render-in-progress nil)
        (goto-char (point-min))))
    (pop-to-buffer buf)))

(defun aw--roster-text ()
  "Resource roster as plain text for AI context."
  (mapconcat (lambda (r) (nth 0 r)) aw--resources ", "))

(defun aw--insert-answer (text)
  "Insert TEXT as a quote block at the end of the current subtree."
  (save-excursion
    (org-end-of-subtree t)
    (insert "\\n#+BEGIN_QUOTE\\n" (or text "(empty answer)") "\\n#+END_QUOTE\\n"))
  (message "AW: answer inserted"))

(defun aw-ask (prompt)
  "Ask the AI about the record subtree under point.

Plain-text advantage: the current Org subtree (headline, properties,
notes) plus the resource roster become the context.  Uses gptel when
installed, else the OpenAI-compatible endpoint in `aw-ai-base-url'."
  (interactive "sAsk about this record: ")
  (let* ((ctx (save-excursion
                (org-back-to-heading t)
                (buffer-substring-no-properties
                 (org-entry-beginning-position) (org-entry-end-position))))
         (full (format "Context (Org record + resource roster):\\n%s\\n\\nResources: %s\\n\\nQuestion: %s"
                       ctx (aw--roster-text) prompt)))
    (if (and aw-use-gptel (featurep 'gptel))
        ;; gptel is async by contract: the callback inserts the answer.
        (gptel-request full :callback
                       (lambda (resp _info) (aw--insert-answer resp)))
      (aw--insert-answer (aw--ask-openai full)))))

(defun aw--ask-openai (prompt)
  "Send PROMPT to the OpenAI-compatible endpoint (raw url.el path)."
  (let* ((url (concat aw-ai-base-url "/chat/completions"))
         (url-request-method "POST")
         (url-request-extra-headers
          `(("Content-Type" . "application/json")
            ("Authorization" . ,(concat "Bearer "
                               (or (auth-source-pick-first-password :host aw-ai-base-url)
                                   (getenv "AW_AI_API_KEY") "")))))
         (url-request-data
          (json-encode `((model . ,aw-ai-model)
                         (messages . [((role . "user") (content . ,prompt))]))))
         (buf (url-retrieve-synchronously url)))
    (unless buf (error "AW: cannot reach %s" url))
    (unwind-protect
        (with-current-buffer buf
          (goto-char (point-min))
          (re-search-forward "\\r\\n\\r\\n" nil t)
          (let ((json-array-type 'list) (json-object-type 'alist)
                (resp (json-read-from-string
                       (decode-coding-string
                        (buffer-substring (point) (point-max)) 'utf-8))))
            (cdr (assq 'content
                       (cdr (assq 'message
                                  (cdr (assq 'choices (elt resp 0))))))))
      (kill-buffer buf))))

(defvar aw-mode-map nil
  "Keys for aw buffers.  Bound after `aw-mode' is defined; everything
else stays plain Org.")

(define-derived-mode aw-mode org-mode "AW"
  "Org admin buffer: paginated records, TODO write-back, AI on plain text."
  ;; Buffer-local hook: only aw buffers sync TODO state to the API.
  (add-hook 'org-after-todo-state-change-hook #'aw--sync-todo nil t))

(let ((m aw-mode-map))
  (define-key m (kbd "+") #'aw--page-next)
  (define-key m (kbd "-") #'aw--page-prev)
  (define-key m (kbd "g") #'aw--refresh)
  (define-key m (kbd "c") #'aw-create)
  (define-key m (kbd "k") #'aw-delete)
  (define-key m (kbd "s") #'aw-save)
  (define-key m (kbd "T") #'aw-todos)
  (define-key m (kbd "a") #'aw-ask))

(provide '__PACKAGE__)
;;; __PACKAGE__.el ends here
'''


def render_elisp(resources: list, api_host: str, package_name: str,
                 version: str = "0.0.0") -> str:
    """Render the Emacs package. Pure string work — deterministic."""
    import time
    # NOTE: the year is the only clock read (copyright line); everything
    # else stays clock-free so regenerations stay byte-identical.
    year = time.strftime("%Y")
    return (_TEMPLATE
            .replace("__RESOURCES__", _el_resources(resources))
            .replace("__ROSTER__", _el_roster(resources))
            .replace("__API_HOST__", api_host)
            .replace("__PACKAGE__", package_name)
            .replace("__FIRST_RESOURCE__", resources[0]["name"] if resources else "")
            .replace("__VERSION__", version)
            .replace("__YEAR__", year))
